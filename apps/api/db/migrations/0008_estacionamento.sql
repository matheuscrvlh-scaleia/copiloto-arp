-- Estacionamento (WPS): tudo o que a API BI da WPS entrega, para a tela
-- Financeiro › Estacionamento. Pagamentos e movimento por tipo de veículo já
-- existiam (0001_base); aqui entram os acessos por hora, os eventos do dia
-- (descontos, validações, selos, abonos, manobras, cancelamentos, aberturas
-- manuais, troco, limpeza de pátio), os contratos de mensalistas e
-- credenciados, as mensalidades e os dados da garagem.
--
-- LGPD: nada de placa, CPF/CNPJ, cartão de acesso, nome de operador ou nome
-- de cliente pessoa física. Só a sincronização (service role) grava.

-- 1. Permissão da tela. Quem já vê o painel financeiro passa a ver também.
insert into core.permissoes (codigo, descricao)
values (
  'financeiro.estacionamento',
  'Ver o estacionamento: receita, fluxo, benefícios e mensalistas (WPS)'
)
on conflict do nothing;

insert into core.cargo_permissoes (cargo_id, permissao)
select cargo_id, 'financeiro.estacionamento'
from core.cargo_permissoes
where permissao = 'financeiro.painel'
on conflict do nothing;

insert into core.usuario_permissoes (usuario_id, permissao)
select usuario_id, 'financeiro.estacionamento'
from core.usuario_permissoes
where permissao = 'financeiro.painel'
on conflict do nothing;

-- 2. Pagamentos e movimento: a tela nova também lê.
drop policy ver on financeiro.estacionamento_pagamentos;
create policy ver on financeiro.estacionamento_pagamentos
  for select to authenticated
  using (
    (select core.pode('financeiro.estacionamento'))
    or (select core.pode('financeiro.painel'))
    or (select core.pode('financeiro.fluxo_de_caixa'))
    or (select core.pode('financeiro.performance_capital'))
  );

drop policy ver on financeiro.estacionamento_movimento;
create policy ver on financeiro.estacionamento_movimento
  for select to authenticated
  using (
    (select core.pode('financeiro.estacionamento'))
    or (select core.pode('financeiro.painel'))
    or (select core.pode('financeiro.fluxo_de_caixa'))
    or (select core.pode('financeiro.performance_capital'))
  );

-- 3. Entradas e saídas somadas por hora, tipo de cliente (ROTATIVO,
-- MENSALISTA, CREDENCIADO, CARENCIA), tipo de veículo e serviço (COMUM,
-- VALLET, SEM PARAR…; '' quando a WPS não informa). Sem ticket nem placa.
create table financeiro.estacionamento_acessos (
  estacionamento_id integer not null,
  data date not null,
  sentido text not null check (sentido in ('entrada', 'saida')),
  hora smallint not null check (hora between 0 and 23),
  tipo_cliente text not null,
  tipo_veiculo text not null,
  servico text not null default '',
  quantidade integer not null check (quantidade > 0),
  -- Tickets cancelados na entrada (já contados em quantidade).
  cancelados integer not null default 0 check (cancelados >= 0),
  sync_run_id uuid references integracao.sync_runs (id) on delete set null,
  atualizado_em timestamptz not null default now(),
  primary key (
    estacionamento_id, data, sentido, hora, tipo_cliente, tipo_veiculo, servico
  )
);

create index estacionamento_acessos_sync_run
  on financeiro.estacionamento_acessos (sync_run_id)
  where sync_run_id is not null;

-- 4. Um registro por ocorrência do dia, de cada tipo. Cada (dia, tipo) é
-- trocado inteiro quando a leitura daquele tipo dá certo.
--   categoria: convênio do desconto, tipo do selo/abono, evento da manobra,
--              tipo da validação (HIPERMERCADO, CONVENIO_CPF), forma do
--              pagamento cancelado, descrição da devolução de troco.
--   situacao:  status do selo/abono gerado; ISENCOES/PAGANTES na validação.
--   detalhe:   terminal, justificativa, validador, loja que comprou o selo.
--   valor:     R$ descontado, abonado, cancelado ou devolvido.
--   quantidade: veículos removidos na limpeza de pátio; 1 nos outros.
--   dados:     o resto que a WPS manda (minutos, tarifa, lote…), sem dado
--              pessoal.
create table financeiro.estacionamento_eventos (
  id bigint generated by default as identity primary key,
  estacionamento_id integer not null,
  data date not null,
  tipo text not null check (tipo = any (array[
    'cancela_manual_entrada', 'cancela_manual_saida', 'pagamento_cancelado',
    'devolucao_troco', 'manutencao_patio', 'desconto', 'validacao',
    'abono_utilizado', 'abono_gerado', 'selo_utilizado', 'selo_gerado',
    'manobra'
  ])),
  ocorrido_em timestamp,
  ticket text,
  categoria text,
  situacao text,
  detalhe text,
  setor text,
  valor numeric(14, 2),
  quantidade integer not null default 1 check (quantidade >= 0),
  dados jsonb not null default '{}'::jsonb,
  sync_run_id uuid references integracao.sync_runs (id) on delete set null,
  atualizado_em timestamptz not null default now()
);

create index estacionamento_eventos_dia
  on financeiro.estacionamento_eventos (estacionamento_id, data, tipo);
create index estacionamento_eventos_sync_run
  on financeiro.estacionamento_eventos (sync_run_id)
  where sync_run_id is not null;

-- 5. Contratos de vaga (mensalistas e credenciados), como estão hoje. A
-- sincronização troca a lista inteira do estacionamento. `cliente` só vem
-- quando é pessoa jurídica (loja, empresa).
create table financeiro.estacionamento_contratos (
  id bigint generated by default as identity primary key,
  estacionamento_id integer not null,
  -- 0: credenciado (não gera contrato).
  contrato bigint not null,
  tipo text not null,
  situacao text not null,
  cliente text,
  plano text,
  valor_mensalidade numeric(14, 2) not null default 0,
  vagas integer not null default 0,
  usuarios integer not null default 0,
  veiculos integer not null default 0,
  grupo_acesso text,
  criado_em date,
  sync_run_id uuid references integracao.sync_runs (id) on delete set null,
  atualizado_em timestamptz not null default now()
);

create index estacionamento_contratos_estacionamento
  on financeiro.estacionamento_contratos (estacionamento_id, contrato);
create index estacionamento_contratos_sync_run
  on financeiro.estacionamento_contratos (sync_run_id)
  where sync_run_id is not null;

-- 6. Mensalidades (lançamentos financeiros dos contratos). A sincronização
-- troca a janela de vencimentos que leu.
create table financeiro.estacionamento_mensalidades (
  id bigint generated by default as identity primary key,
  estacionamento_id integer not null,
  contrato bigint not null,
  status_contrato text,
  contrato_inicio timestamp,
  contrato_fim timestamp,
  vencimento date not null,
  pago_em timestamp,
  forma_pagamento text,
  valor numeric(14, 2) not null,
  valor_pago numeric(14, 2) not null default 0,
  status text not null,
  sync_run_id uuid references integracao.sync_runs (id) on delete set null,
  atualizado_em timestamptz not null default now()
);

create index estacionamento_mensalidades_vencimento
  on financeiro.estacionamento_mensalidades (estacionamento_id, vencimento);
create index estacionamento_mensalidades_sync_run
  on financeiro.estacionamento_mensalidades (sync_run_id)
  where sync_run_id is not null;

-- 7. Cadastro da garagem na WPS (capacidade e setores). A chave e a senha da
-- API que a WPS devolve junto nunca são gravadas.
create table financeiro.estacionamento_garagens (
  estacionamento_id integer primary key,
  descricao text,
  cidade text,
  uf text,
  vagas integer,
  vagas_mensalistas integer,
  -- Clientes com vaga que a WPS conta. A lista com detalhe (contratos) vem
  -- incompleta da WPS; estes totais são os que valem.
  clientes_mensalistas integer,
  clientes_credenciados integer,
  -- [{ codigo, setor, sla, sla2, tempo_pos_checkout }]
  setores jsonb not null default '[]'::jsonb,
  sync_run_id uuid references integracao.sync_runs (id) on delete set null,
  atualizado_em timestamptz not null default now()
);

create index estacionamento_garagens_sync_run
  on financeiro.estacionamento_garagens (sync_run_id)
  where sync_run_id is not null;

create trigger atualizado_em before update on financeiro.estacionamento_garagens
  for each row execute function core.set_atualizado_em();

-- 8. Leitura: quem vê a tela do estacionamento. Gravação: só a service role.
do $$
declare
  t text;
begin
  foreach t in array array[
    'estacionamento_acessos', 'estacionamento_eventos',
    'estacionamento_contratos', 'estacionamento_mensalidades',
    'estacionamento_garagens'
  ] loop
    execute format('alter table financeiro.%I enable row level security', t);
    execute format(
      'create policy ver on financeiro.%I for select to authenticated '
      'using ((select core.pode(''financeiro.estacionamento'')))', t
    );
    execute format('revoke all on financeiro.%I from public, anon, authenticated', t);
    execute format('grant select on financeiro.%I to authenticated', t);
    execute format(
      'grant select, insert, update, delete on financeiro.%I to service_role', t
    );
  end loop;
end
$$;
